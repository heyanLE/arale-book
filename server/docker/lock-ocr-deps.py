#!/usr/bin/env python3
"""Refresh the Linux CPython 3.12 wheel lock from PyPI (explicit maintenance command)."""
import json
import urllib.request
from pathlib import Path

PACKAGES = {
    'onnxruntime': '1.30.0', 'numpy': '2.5.3',
    'opencv-python-headless': '5.0.0.93', 'scipy': '1.18.1',
    'pillow': '12.3.0', 'pyclipper': '1.4.0',
    'shapely': '2.1.2', 'jaconv': '0.5.0',
    'packaging': '26.3', 'flatbuffers': None, 'protobuf': None,
}

def main():
    lines = ['# Linux amd64/arm64, CPython 3.12. Generated by lock-ocr-deps.py.',
             '# All direct and transitive dependencies are pinned and hashed.']
    for name, version in PACKAGES.items():
        url = f'https://pypi.org/pypi/{name}/' + (f'{version}/json' if version else 'json')
        with urllib.request.urlopen(url, timeout=45) as response:
            metadata = json.load(response)
        version = metadata['info']['version']
        wheels = []
        for entry in metadata['urls']:
            filename = entry['filename']
            compatible = ('-cp312-cp312-' in filename or '-abi3-' in filename)
            linux = 'manylinux' in filename and ('x86_64' in filename or 'aarch64' in filename)
            pure = filename.endswith(('-py3-none-any.whl', '-py2.py3-none-any.whl'))
            if pure or (compatible and linux):
                wheels.append(entry)
        if not wheels:
            raise RuntimeError(f'No supported binary wheel: {name} {version}')
        hashes = sorted(set(entry['digests']['sha256'] for entry in wheels))
        lines.append(name + '==' + version + ' \\\n    ' + ' \\\n    '.join('--hash=sha256:' + digest for digest in hashes))
        print(name, version, len(wheels), 'wheels')
    Path(__file__).with_name('requirements-linux.lock').write_text('\n'.join(lines) + '\n')

if __name__ == '__main__':
    main()
