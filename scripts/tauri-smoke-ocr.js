window.__araleOcrSmoke = async ({check,until,evidence,dataRoot,imageNovel}) => {
  const api=window.arale;
  const initial=await api.extensions.list();
  check('bundled OCR repository exposes official Windows package',initial.statuses.some(v=>v.entry.id==='ocr-arale_onnx_v1' && v.entry.bytes>700000000));
  for(const repo of initial.repositories) await api.extensions.removeRepository(repo.url);
  check('removing all repositories keeps them empty',(await api.extensions.list()).repositories.length===0);
  check('repository requires HTTPS JSONL',!(await api.extensions.addRepository('unsafe','http://example.invalid/index.jsonl')).ok);
  await api.extensions.addRepository('Smoke','https://tauri-smoke.invalid/extension.jsonl');
  check('native repository refresh validates streamed JSONL',(await api.extensions.refresh()).ok);
  check('extension SHA mismatch rejects unpublished package',!(await api.extensions.install('ocr-badhash')).ok);
  check('manifest identity mismatch rejects package',!(await api.extensions.install('ocr-wrong')).ok);
  const install=api.extensions.install('ocr-download-slow');
  await new Promise(resolve=>setTimeout(resolve,350));await api.extensions.cancel('ocr-download-slow');
  check('native extension download cancels promptly',!(await install).ok);
  check('native verified extension publishes atomically',(await api.extensions.install('ocr-smoke')).ok && (await api.extensions.list()).statuses.find(v=>v.entry.id==='ocr-smoke').installed);
  check('second engine installed',(await api.extensions.install('ocr-slow')).ok);
  await api.ocr.selectProvider('arale_onnx_v1');
  const capability=await api.ocr.capability();
  check('installed engine appears ready and selected',capability.selected==='arale_onnx_v1' && capability.providers.find(v=>v.id==='arale_onnx_v1').ready);
  const imports=await api.library.importPaths([`${dataRoot}/ocr-a.cbz`,`${dataRoot}/ocr-b.cbz`,`${dataRoot}/ocr-system.cbz`]);
  check('OCR-only books imported',imports.every(v=>v.ok));
  const [a,b,system]=imports.map(v=>v.bookId);evidence.ocrIds=[a];evidence.ocrReloadId=b;
  const progress=[]; const sub=api.on('ocr:progress',v=>progress.push(v));
  await api.ocr.start(a,{force:true});
  await until(async()=>!(await api.ocr.queue()).active,'extension OCR');
  check('native OCR completes all pages',(await api.ocr.status(a)).ok && (await api.ocr.status(a)).pages===4);
  check('NDJSON produces actual progress and shared blocks',progress.filter(v=>v.bookId===a && v.stage==='recognizing').length===4 && (await api.book.pageText(a,0)).blocks.some(v=>v.lines.join('').includes('猫')));
  check('OCR skip retains existing text',(await api.ocr.start(a)).skipped);
  await api.ocr.start(a,{force:true,provider:'smoke_slow'});
  await until(()=>progress.some(v=>v.bookId===a && v.provider==='smoke_slow' && v.done===1),'first page before cancel');
  check('busy OCR extension cannot be removed',!(await api.extensions.remove('ocr-slow')).ok);
  check('busy OCR extension cannot be overwritten',!(await api.extensions.install('ocr-slow')).ok);
  check('OCR blocks book deletion',await api.library.remove([a]).then(()=>false,()=>true));
  await api.ocr.start(b,{force:true});
  check('OCR FIFO enqueues second book',(await api.ocr.queue()).pending[0]?.bookId===b);
  await api.ocr.cancel(b);
  check('cancel waiting OCR job leaves it unstarted',(await api.ocr.status(b)).error.includes('还没开始') && (await api.ocr.queue()).pending.length===0);
  await api.ocr.cancel(a);
  await until(async()=>!(await api.ocr.queue()).active,'active OCR cancellation');
  check('cancel OCR saves first page and preserves old later pages',!(await api.ocr.status(a)).ok && (await api.ocr.status(a)).pages===1 && (await api.book.pageText(a,3)).blocks.some(v=>v.lines.join('').includes('猫')));
  await api.ocr.start(b,{force:true,provider:'smoke_slow'});
  await until(()=>progress.some(v=>v.bookId===b && v.done===1),'page before source conflict');
  const before=(await api.library.open(b)).book.direction;
  await api.library.updateMeta(b,{direction:before==='rtl'?'ltr':'rtl'});await api.ocr.cancel(b);
  await until(async()=>!(await api.ocr.queue()).active,'source conflict');
  check('source change prevents overwriting prior OCR layer',(await api.ocr.status(b)).error.includes('已变化') && (await api.book.pageText(b,0)).blocks.length===0);
  await api.library.updateMeta(b,{direction:before});
  if(capability.providers[0].ready){
    await api.ocr.start(system,{force:true,provider:'system'});
    await until(async()=>!(await api.ocr.queue()).active,'real Windows.Media.Ocr');
    const systemStatus=await api.ocr.status(system);evidence.systemOcr=systemStatus;
    check('real Windows system OCR finishes pages '+JSON.stringify(systemStatus),systemStatus.ok && systemStatus.blocks>0);evidence.ocrIds.push(system);
  } else throw new Error('Windows system OCR required for this test: '+capability.providers[0].reason);
  await api.extensions.remove('ocr-smoke');await api.extensions.remove('ocr-slow');
  for(const repo of initial.repositories) await api.extensions.addRepository(repo.name,repo.url);
  const dev=(await api.extensions.list()).statuses.find(v=>v.installed?.local);
  if(dev){
    await api.ocr.start(b,{force:true,provider:'arale_onnx_v1'});
    await until(async()=>!(await api.ocr.queue()).active,'real Python ONNX OCR');
    check('real bundled Python/ORT runner generates blocks',(await api.ocr.status(b)).ok && (await api.ocr.status(b)).blocks>0);evidence.ocrIds.push(b);
  }
  await api.extensions.install('ocr-smoke');
  await api.ocr.start(imageNovel.id,{force:true,provider:'arale_onnx_v1'});
  await until(async()=>!(await api.ocr.queue()).active,'image EPUB OCR');
  check('image EPUB OCR preserves EPUB format',(await api.ocr.status(imageNovel.id)).ok && (await api.library.open(imageNovel.id)).book.format==='epub');evidence.ocrIds.push(imageNovel.id);
  api.off(sub);
  await api.ocr.start(b,{force:true,provider:'arale_onnx_v1'});
};
